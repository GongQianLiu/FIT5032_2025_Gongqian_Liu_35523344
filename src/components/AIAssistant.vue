<script>
import { ref, onMounted, nextTick, watch } from 'vue';
import { useToast } from 'vue-toastification';
import { Modal } from 'bootstrap';
import enhancedAIService from '../services/enhancedAIService';

export default {
  name: 'AIAssistant',
  setup() {
    const toast = useToast();
    
    // Chat state
    const chatContainer = ref(null);
    const messageInput = ref(null);
    const currentMessage = ref('');
    const chatHistory = ref([]);
    const isLoading = ref(false);
    const aiStatus = ref('connecting');
    const userRole = ref('user'); // Add user role state
    
    // Usage statistics
    const usageStats = ref({
      totalConversations: 0,
      totalMessages: 0,
      averageResponseTime: 0,
      successRate: 100
    });

    // Task analysis form
    const taskAnalysisForm = ref({
      description: '',
      type: '',
      context: ''
    });
    const taskAnalysisResult = ref('');

    // Health tips form
    const healthTipsForm = ref({
      topic: '',
      age: '',
      condition: ''
    });
    const healthTipsResult = ref('');

    // Get user role from localStorage
    const getUserRole = () => {
      try {
        const userStr = localStorage.getItem('currentUser');
        if (userStr) {
          const user = JSON.parse(userStr);
          return user.role || 'user';
        }
      } catch (error) {
        console.error('Failed to parse user information:', error);
      }
      return 'user';
    };

    // Initialize user role
    const initUserRole = () => {
      userRole.value = getUserRole();
    };

    // Quick suggestions based on user role
    const getQuickSuggestions = () => {
      const baseSuggestions = [
      'How do I create a new task?',
      'How can I improve my rating?',
      'Tell me about health services',
      'Help me with system navigation'
    ];

      if (userRole.value === 'elderly') {
        return [
          ...baseSuggestions,
          'How do I rate a volunteer?',
          'How do I book a health appointment?',
          'What types of tasks can I create?',
          'How do I check my task status?'
        ];
      } else if (userRole.value === 'volunteer') {
        return [
          ...baseSuggestions,
          'How do I accept a task?',
          'What are the best practices for volunteers?',
          'How do I complete a task?',
          'How can I improve my volunteer rating?'
        ];
      } else if (userRole.value === 'admin') {
        return [
          ...baseSuggestions,
          'How do I manage users?',
          'How do I send bulk emails?',
          'How do I view system statistics?',
          'How do I manage health services?'
        ];
      }

      return baseSuggestions;
    };

    const quickSuggestions = getQuickSuggestions();

    // Test AI connection
    const testConnection = async () => {
      try {
        isLoading.value = true;
        const startTime = Date.now();
        
        const result = await enhancedAIService.callAIAssistant('Hello, can you hear me?');
        
        const responseTime = (Date.now() - startTime) / 1000;
        usageStats.value.averageResponseTime = responseTime;
        
        if (result.success) {
          aiStatus.value = 'connected';
          toast.success('AI connection successful!');
          addMessage('assistant', result.response, 'silicon-flow-qwen2.5');
        } else {
          throw new Error('AI response failed');
        }
      } catch (error) {
        console.error('Connection test failed:', error);
        aiStatus.value = 'offline';
        toast.error('AI connection failed. Using fallback mode.');
      } finally {
        isLoading.value = false;
      }
    };

    // Load chat history from localStorage
    const loadChatHistory = () => {
      try {
        const saved = localStorage.getItem('ai_chat_history');
        if (saved) {
          const parsed = JSON.parse(saved);
          // Only load if it's from today (to avoid old conversations)
          const today = new Date().toDateString();
          if (parsed.date === today && Array.isArray(parsed.history)) {
            chatHistory.value = parsed.history.map(msg => ({
              ...msg,
              timestamp: new Date(msg.timestamp)
            }));
            return true;
          }
        }
      } catch (error) {
        console.warn('Failed to load chat history:', error);
      }
      return false;
    };

    // Save chat history to localStorage
    const saveChatHistory = () => {
      try {
        const toSave = {
          date: new Date().toDateString(),
          history: chatHistory.value
        };
        localStorage.setItem('ai_chat_history', JSON.stringify(toSave));
      } catch (error) {
        console.warn('Failed to save chat history:', error);
      }
    };

    // Initialize AI Assistant
    const initializeAI = async () => {
      // Load existing chat history first
      const hasHistory = loadChatHistory();

      // Set AI status to connected immediately to avoid browser extension conflicts
      aiStatus.value = 'connected';

      try {
        // Use a safer initialization approach
        setTimeout(async () => {
          try {
            const testResult = await enhancedAIService.testConnection();
            if (testResult.provider === 'claude') {
              toast.success('AI Assistant ready (Claude AI) - Powered by Anthropic Claude technology');
            } else if (testResult.provider === 'local-ai') {
              toast.success('AI Assistant ready (Advanced Local AI) - Providing intelligent, context-aware responses');
            } else if (testResult.provider === 'silicon-flow') {
              toast.success('AI Assistant ready (Silicon Flow AI) - Real AI powered responses');
            } else if (testResult.provider === 'enhanced-mock') {
              toast.success('AI Assistant ready (Smart Mode) - Providing intelligent responses');
            } else {
              toast.success(`AI Assistant ready (${testResult.provider})`);
            }
          } catch (error) {
            console.warn('AI test connection failed, but continuing in safe mode:', error);
            toast.success('AI Assistant ready (Safe Mode)');
          }
        }, 100); // Small delay to avoid extension conflicts

      } catch (error) {
        console.warn('AI initialization error:', error);
        // Still set as connected since we have mock responses
        aiStatus.value = 'connected';
        toast.success('AI Assistant ready (Safe Mode)');
      }

      // Only add welcome message if no history exists
      if (!hasHistory) {
        // Get personalized welcome message based on user role
        const getWelcomeMessage = () => {
        const baseMessage = `Hello! I'm your AI assistant for the Evergreen Way platform. I'm powered by Claude AI technology and ready to provide intelligent, helpful responses.`;

        if (userRole.value === 'elderly') {
          return `${baseMessage}

As an elderly user, I can help you with:
• **Task Management**: Creating and tracking help requests
• **Volunteer Services**: Understanding how volunteers can assist you
• **Health Appointments**: Booking and managing health services
• **Rating System**: How to rate volunteers after service
• **System Navigation**: Finding features and getting help

Testing connection to AI services...`;
        } else if (userRole.value === 'volunteer') {
          return `${baseMessage}

As a volunteer, I can help you with:
• **Task Acceptance**: How to find and accept tasks
• **Service Best Practices**: Tips for providing excellent service
• **Task Completion**: How to properly complete and update tasks
• **Rating Improvement**: How to maintain high ratings
• **System Navigation**: Finding features and getting help

Testing connection to AI services...`;
        } else if (userRole.value === 'admin') {
          return `${baseMessage}

As an administrator, I can help you with:
• **User Management**: Managing elderly and volunteer accounts
• **System Monitoring**: Viewing statistics and system health
• **Email Management**: Sending bulk emails and notifications
• **Service Management**: Managing health services and events
• **Data Analysis**: Understanding system usage and trends

Testing connection to AI services...`;
        }

        return `${baseMessage}

I can help you with:
• **Task Management**: Creating, editing, and tracking tasks
• **System Navigation**: Finding features and understanding the interface
• **Best Practices**: Tips for volunteers and elderly users
• **Health & Wellness**: Information about health services and activities
• **General Support**: Any questions about the Evergreen Way system

Testing connection to AI services...`;
        };

        // Add welcome message
        addMessage('assistant', getWelcomeMessage());

        // Test connection
        testConnection();
      }
    };

    // Add message to chat
    const addMessage = (role, content, model = null) => {
      chatHistory.value.push({
        role,
        content,
        timestamp: new Date(),
        model
      });
      
      // Update stats
      if (role === 'user') {
        usageStats.value.totalMessages++;
      }

      // Auto-save chat history
      saveChatHistory();

      // Scroll to bottom
      nextTick(() => {
        scrollToBottom();
      });
    };

    // Send message
    const sendMessage = async (message) => {
      if (!message.trim() || isLoading.value) return;
      
      const userMessage = message.trim();
      currentMessage.value = '';
      
      // Add user message
      addMessage('user', userMessage);
      
      // Show loading
      isLoading.value = true;
      
      try {
        const startTime = Date.now();
        
        // Use enhanced AI service
        const conversationHistory = chatHistory.value
          .filter(msg => msg.role !== 'system')
          .slice(-10) // Keep last 10 messages for context
          .map(msg => ({ role: msg.role, content: msg.content }));

        const result = await enhancedAIService.callAIAssistant(userMessage, conversationHistory);

        if (result.success) {
          addMessage('assistant', result.response, result.provider);
          usageStats.value.totalConversations++;
          usageStats.value.successRate = 100;

          // Update AI status based on provider
          if (result.provider === 'gemini') {
            aiStatus.value = 'connected';
          } else if (result.provider === 'mock') {
            aiStatus.value = 'offline';
            toast.warning('Using fallback AI responses');
          }
        } else {
          throw new Error(result.error || 'AI response failed');
        }
        
        // Update response time
        const responseTime = (Date.now() - startTime) / 1000;
        usageStats.value.averageResponseTime = responseTime;
        
      } catch (error) {
        console.error('AI response error:', error);

        // Fallback to offline mode
        aiStatus.value = 'offline';
        const fallbackMessage = "I apologize, but I'm having trouble connecting to the AI service right now. Please try again later or contact support for immediate assistance.";
        addMessage('assistant', fallbackMessage, 'error');

        toast.error('AI service unavailable. Please try again later.');
        usageStats.value.successRate = Math.max(0, usageStats.value.successRate - 10);
      } finally {
        isLoading.value = false;
      }
    };

    // Show task analysis modal
    const showTaskAnalysis = () => {
      const modal = new Modal(document.getElementById('taskAnalysisModal'));
      modal.show();
    };

    // Analyze task
    const analyzeTask = async () => {
      if (!taskAnalysisForm.value.description) return;

      try {
        isLoading.value = true;

        // Use AI assistant to analyze task
        const prompt = `Please analyze this task: "${taskAnalysisForm.value.description}". Task type: ${taskAnalysisForm.value.type}. Context: ${taskAnalysisForm.value.context}.

Please provide:
1. Task complexity assessment
2. Estimated time required
3. Required skills or resources
4. Potential challenges
5. Recommendations for successful completion
6. Safety considerations (if applicable)`;

        const result = await enhancedAIService.callAIAssistant(prompt);

        if (result.success) {
          taskAnalysisResult.value = result.response;
          toast.success('Task analysis completed!');
        } else {
          throw new Error('Task analysis failed');
        }
      } catch (error) {
        console.error('Task analysis error:', error);
        toast.error('Failed to analyze task. Please try again.');
        // Provide fallback analysis
        taskAnalysisResult.value = `Task Analysis for: ${taskAnalysisForm.value.description}\n\nType: ${taskAnalysisForm.value.type}\n\nGeneral Recommendations:\n• Break down the task into smaller steps\n• Ensure you have necessary resources\n• Consider safety precautions\n• Allow adequate time for completion\n• Ask for help if needed\n\nFor detailed analysis, please try again or consult with a volunteer coordinator.`;
      } finally {
        isLoading.value = false;
      }
    };

    // Show health tips modal
    const showHealthTips = () => {
      const modal = new Modal(document.getElementById('healthTipsModal'));
      modal.show();
    };

    // Get health tips
    const getHealthTips = async () => {
      if (!healthTipsForm.value.topic) return;

      try {
        isLoading.value = true;

        // Use AI assistant to generate health tips
        const prompt = `Please provide health tips for ${healthTipsForm.value.topic} for a ${healthTipsForm.value.age} year old person${healthTipsForm.value.condition ? ` with ${healthTipsForm.value.condition}` : ''}. Please provide practical, safe, and helpful advice.`;

        const result = await enhancedAIService.callAIAssistant(prompt);

        if (result.success) {
          healthTipsResult.value = result.response;
          toast.success('Health tips generated!');
        } else {
          throw new Error('Health tips generation failed');
        }
      } catch (error) {
        console.error('Health tips error:', error);
        toast.error('Failed to get health tips. Please try again.');
        // Provide fallback health tips
        healthTipsResult.value = `Here are some general health tips for ${healthTipsForm.value.topic}:\n\n• Stay hydrated by drinking plenty of water\n• Maintain a balanced diet with fruits and vegetables\n• Get regular exercise appropriate for your age\n• Ensure adequate sleep (7-9 hours per night)\n• Regular check-ups with healthcare providers\n• Practice stress management techniques\n\nPlease consult with healthcare professionals for personalized advice.`;
      } finally {
        isLoading.value = false;
      }
    };

    // Handle Enter key
    const handleEnter = (event) => {
      if (event.shiftKey) {
        // Allow new line with Shift+Enter
        return;
      }
      sendMessage(currentMessage.value);
    };

    // Scroll to bottom
    const scrollToBottom = () => {
      if (chatContainer.value) {
        chatContainer.value.scrollTop = chatContainer.value.scrollHeight;
      }
    };

    // Clear chat
    const clearChat = () => {
      if (confirm('Are you sure you want to clear the chat history?')) {
        chatHistory.value = [];
        localStorage.removeItem('ai_chat_history');
        initializeAI();
        toast.info('Chat history cleared');
      }
    };

    // Export chat
    const exportChat = () => {
      const chatText = chatHistory.value.map(msg => 
        `[${msg.role.toUpperCase()}] ${formatTime(msg.timestamp)}\n${msg.content}\n`
      ).join('\n');
      
      const blob = new Blob([chatText], { type: 'text/plain' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = `ai-chat-${new Date().toISOString().split('T')[0]}.txt`;
      link.click();
      URL.revokeObjectURL(url);
      
      toast.success('Chat exported successfully');
    };

    // Format message content
    const formatMessage = (content) => {
      // Convert markdown-like formatting to HTML
      return content
        .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
        .replace(/\*(.*?)\*/g, '<em>$1</em>')
        .replace(/\n/g, '<br>')
        .replace(/•/g, '&bull;');
    };

    // Format time
    const formatTime = (timestamp) => {
      return new Date(timestamp).toLocaleTimeString('en-US', {
        hour: '2-digit',
        minute: '2-digit'
      });
    };

    // Watch for new messages to scroll
    watch(chatHistory, () => {
      nextTick(() => {
        scrollToBottom();
      });
    });

    onMounted(() => {
      // Clear any browser extension errors
      try {
        if (typeof chrome !== 'undefined' && chrome.runtime) {
          chrome.runtime.lastError = null;
        }
      } catch (e) {
        // Ignore extension-related errors
      }

      initUserRole(); // Initialize user role on mount

      // Delay AI initialization to avoid extension conflicts
      setTimeout(() => {
        initializeAI();
      }, 300);
    });

    return {
      chatContainer,
      messageInput,
      currentMessage,
      chatHistory,
      isLoading,
      aiStatus,
      userRole,
      usageStats,
      quickSuggestions,
      taskAnalysisForm,
      taskAnalysisResult,
      healthTipsForm,
      healthTipsResult,
      sendMessage,
      handleEnter,
      clearChat,
      exportChat,
      formatMessage,
      formatTime,
      testConnection,
      showTaskAnalysis,
      analyzeTask,
      showHealthTips,
      getHealthTips
    };
  }
};
</script>

