                <span>Task Analysis & Recommendations</span>
              </div>
              <div class="feature-item">
                <i class="bi bi-check-circle text-success"></i>
                <span>Health & Wellness Tips</span>
              </div>
              <div class="feature-item">
                <i class="bi bi-check-circle text-success"></i>
                <span>Personalized Assistance</span>
              </div>
            </div>
          </div>
        </div>
      </div>
      
      <div class="col-md-6">
        <div class="card">
          <div class="card-header">
            <h6 class="mb-0">
              <i class="bi bi-graph-up me-2"></i>
              Usage Statistics
            </h6>
          </div>
          <div class="card-body">
            <div class="stats-grid">
              <div class="stat-item">
                <div class="stat-number">{{ usageStats.totalConversations }}</div>
                <div class="stat-label">Conversations</div>
              </div>
              <div class="stat-item">
                <div class="stat-number">{{ usageStats.totalMessages }}</div>
                <div class="stat-label">Messages</div>
              </div>
              <div class="stat-item">
                <div class="stat-number">{{ usageStats.averageResponseTime }}s</div>
                <div class="stat-label">Avg Response</div>
              </div>
              <div class="stat-item">
                <div class="stat-number">{{ usageStats.successRate }}%</div>
                <div class="stat-label">Success Rate</div>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>

    <!-- Task Analysis Modal -->
    <div class="modal fade" id="taskAnalysisModal" tabindex="-1">
      <div class="modal-dialog modal-lg">
        <div class="modal-content">
          <div class="modal-header">
            <h5 class="modal-title">AI Task Analysis</h5>
            <button type="button" class="btn-close" data-bs-dismiss="modal"></button>
          </div>
          <div class="modal-body">
            <div class="mb-3">
              <label class="form-label">Task Description:</label>
              <textarea 
                class="form-control" 
                v-model="taskAnalysisForm.description" 
                rows="3"
                placeholder="Describe the task you need help with..."
              ></textarea>
            </div>
            <div class="row">
              <div class="col-md-6">
                <label class="form-label">Task Type:</label>
                <select class="form-select" v-model="taskAnalysisForm.type">
                  <option value="">Select type...</option>
                  <option value="shopping">Shopping</option>
                  <option value="housework">Housework</option>
                  <option value="companionship">Companionship</option>
                  <option value="health">Health</option>
                  <option value="transportation">Transportation</option>
                  <option value="other">Other</option>
                </select>
              </div>
              <div class="col-md-6">
                <label class="form-label">User Context:</label>
                <select class="form-select" v-model="taskAnalysisForm.context">
                  <option value="elderly">Elderly User</option>
                  <option value="volunteer">Volunteer</option>
                  <option value="admin">Admin</option>
                </select>
              </div>
            </div>
            <div v-if="taskAnalysisResult" class="mt-3">
              <h6>AI Analysis:</h6>
              <div class="analysis-result" v-html="formatMessage(taskAnalysisResult)"></div>
            </div>
          </div>
          <div class="modal-footer">
            <button type="button" class="btn btn-secondary" data-bs-dismiss="modal">Close</button>
            <button 
              type="button" 
              class="btn btn-primary" 
              @click="analyzeTask"
              :disabled="!taskAnalysisForm.description || isLoading"
            >
              <span v-if="isLoading" class="spinner-border spinner-border-sm me-2"></span>
              Analyze Task
            </button>
          </div>
        </div>
      </div>
    </div>

    <!-- Health Tips Modal -->
    <div class="modal fade" id="healthTipsModal" tabindex="-1">
      <div class="modal-dialog modal-lg">
        <div class="modal-content">
          <div class="modal-header">
            <h5 class="modal-title">AI Health Tips</h5>
            <button type="button" class="btn-close" data-bs-dismiss="modal"></button>
          </div>
          <div class="modal-body">
            <div class="row">
              <div class="col-md-4">
                <label class="form-label">Health Topic:</label>
                <select class="form-select" v-model="healthTipsForm.topic">
                  <option value="">Select topic...</option>
                  <option value="general wellness">General Wellness</option>
                  <option value="exercise">Exercise</option>
                  <option value="nutrition">Nutrition</option>
                  <option value="mental health">Mental Health</option>
                  <option value="medication">Medication</option>
                  <option value="safety">Safety</option>
                </select>
              </div>
              <div class="col-md-4">
                <label class="form-label">Age Group:</label>
                <select class="form-select" v-model="healthTipsForm.age">
                  <option value="">Select age...</option>
                  <option value="60-70">60-70</option>
                  <option value="70-80">70-80</option>
                  <option value="80-90">80-90</option>
                  <option value="90+">90+</option>
                </select>
              </div>
              <div class="col-md-4">
                <label class="form-label">Health Condition:</label>
                <select class="form-select" v-model="healthTipsForm.condition">
                  <option value="">Select condition...</option>
                  <option value="general">General</option>
                  <option value="diabetes">Diabetes</option>
                  <option value="hypertension">Hypertension</option>
                  <option value="arthritis">Arthritis</option>
                  <option value="heart">Heart Condition</option>
                  <option value="mobility">Mobility Issues</option>
                </select>
              </div>
            </div>
            <div v-if="healthTipsResult" class="mt-3">
              <h6>AI Health Tips:</h6>
              <div class="health-tips-result" v-html="formatMessage(healthTipsResult)"></div>
            </div>
          </div>
          <div class="modal-footer">
            <button type="button" class="btn btn-secondary" data-bs-dismiss="modal">Close</button>
            <button 
              type="button" 
              class="btn btn-primary" 
              @click="getHealthTips"
              :disabled="!healthTipsForm.topic || isLoading"
            >
              <span v-if="isLoading" class="spinner-border spinner-border-sm me-2"></span>
              Get Health Tips
            </button>
          </div>
        </div>
      </div>
    </div>
  </div>
